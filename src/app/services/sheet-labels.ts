export function sheetRu(text: string | null | undefined): string {
  if (!text) return '';
  if (Object.prototype.hasOwnProperty.call(labels, text)) return labels[text];
  const specialized = /^([^()]+)\s*\((.+)\)$/.exec(text);
  if (specialized && Object.prototype.hasOwnProperty.call(labels, specialized[1].trim())) {
    return labels[specialized[1].trim()] + ' (' + specialized[2] + ')';
  }
  return text;
}

export function sheetRuleRef(text: string | undefined): string {
  return (text ?? '').split(' · ').map(part => {
    const translated = sheetRu(part);
    if (translated !== part) return translated;
    const page = /^(.*), pp?\. (\d.*)$/.exec(part);
    return page ? sheetRu(page[1]) + ', с. ' + page[2] : part;
  }).join(' · ');
}

export function sheetModifierText(text: string): string {
  return text.replace(/^(.+?)( (?=[+=-]|\d))/, (_, label: string, space: string) => sheetRu(label) + space)
    .replace(/ percentage points$/, ' п. п.');
}

export function sheetEffectImpact(effect: CharacterEffect): string {
  if (effect.kind === 'modifier') {
    return sheetModifierText(effectImpact(effect));
  }
  return effectImpact(effect).split(' · ').map(part => {
    if (part.startsWith('Checks: ')) return 'Проверки: ' + sheetRu(part.slice(8));
    if (/^\d+ turns?$/.test(part)) return part.replace(/ turns?$/, ' ход.');
    return sheetRu(part.replace(/^(Movement|Initiative|Action Points)(?= -)/, label => sheetRu(label)).replace(/ m$/, ' м'));
  }).join(' · ');
}
